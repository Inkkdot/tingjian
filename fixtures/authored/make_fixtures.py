def fmt(ms: int) -> str:
    h, rem = divmod(ms, 3600_000)
    m, rem = divmod(rem, 60_000)
    s, ms = divmod(rem, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def main() -> None:
    manifest = {"courses": COURSES, "lectures": []}
    for lecture in LECTURES:
        lines = []
        cursor = 4_000
        for i, text in enumerate(lecture["cues"], 1):
            duration = max(2_200, min(6_000, 900 + len(text) * 170))
            start, end = cursor, cursor + duration
            lines += [str(i), f"{fmt(start)} --> {fmt(end)}", text, ""]
            cursor = end + 260
        path = OUT / f"{lecture['id']}.srt"
        path.write_text("\n".join(lines), encoding="utf-8")
        manifest["lectures"].append(
            {
                "id": lecture["id"],
                "course_id": lecture["course"],
                "title": lecture["title"],
                "file": path.name,
                "source_url": "",
                "source_type": "authored_srt",
                "platform": "local",
                "platform_video_id": lecture["id"],
                "part_index": 1,
                "language": "zh",
                "license": "CC BY 4.0 / self-authored for this project",
            }
        )
    (OUT / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(f"wrote {len(manifest['lectures'])} SRT files to {OUT}")


if __name__ == "__main__":
    main()
